-- 1. TABLAS BASE

CREATE TABLE REGION (
    cod_region NUMBER(4) CONSTRAINT PK_REGION PRIMARY KEY,
    nombre_region VARCHAR2(100) NOT NULL
);

CREATE TABLE COMUNA (
    cod_comuna NUMBER(4) CONSTRAINT PK_COMUNA PRIMARY KEY,
    cod_region NUMBER(4) NOT NULL,
    nombre_comuna VARCHAR2(100) NOT NULL,
    CONSTRAINT FK_COMUNA_REGION
        FOREIGN KEY (cod_region) REFERENCES REGION(cod_region)
);

CREATE TABLE ASOCIACION (
    cod_asociacion NUMBER(6) CONSTRAINT PK_ASOCIACION PRIMARY KEY,
    nombre_asociacion VARCHAR2(100) NOT NULL,
    fecha_creacion DATE NOT NULL,
    tipo VARCHAR2(1) NOT NULL,
    CONSTRAINT CK_ASOCIACION_TIPO CHECK (tipo IN ('P','A')),
    CONSTRAINT CK_ASOCIACION_FECHA
        CHECK (fecha_creacion >= DATE '1980-12-31')
);

CREATE TABLE NACIONALIDAD (
    cod_nacionalidad NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 210 INCREMENT BY 2)
        CONSTRAINT PK_NACIONALIDAD PRIMARY KEY,
    nombre_nacionalidad VARCHAR2(50) NOT NULL
);

CREATE TABLE ESCUELA_FUTBOL (
    cod_escuela NUMBER(6) CONSTRAINT PK_ESCUELA_FUTBOL PRIMARY KEY,
    nombre_escuela VARCHAR2(100) NOT NULL,
    capacidad NUMBER(6) NOT NULL,
    fecha_fundacion DATE NOT NULL
);

CREATE TABLE CLUB_FUTBOL (
    cod_club NUMBER(6) CONSTRAINT PK_CLUB_FUTBOL PRIMARY KEY,
    nombre_club VARCHAR2(100) NOT NULL,
    patrimonio NUMBER(14,2) NOT NULL,
    direccion VARCHAR2(100) NOT NULL,
    tipo_club VARCHAR2(20) DEFAULT 'Profesional' NOT NULL,
    cod_asociacion NUMBER(6),
    CONSTRAINT UQ_CLUB_FUTBOL_NOMBRE UNIQUE (nombre_club),
    CONSTRAINT CK_CLUB_FUTBOL_PATRIMONIO CHECK (patrimonio >= 0),
    CONSTRAINT FK_CLUB_FUTBOL_ASOCIACION
        FOREIGN KEY (cod_asociacion)
        REFERENCES ASOCIACION(cod_asociacion)
);

CREATE SEQUENCE SEQ_CLUB_FUTBOL
    START WITH 703
    INCREMENT BY 4
    NOCACHE;

-- 2. SUPERTIPO Y SUBTIPOS

CREATE TABLE TRABAJADOR (
    cod_trabajador NUMBER(6) CONSTRAINT PK_TRABAJADOR PRIMARY KEY,
    rut NUMBER(8) NOT NULL,
    dv VARCHAR2(1) NOT NULL,
    nombres VARCHAR2(50) NOT NULL,
    apellidos VARCHAR2(50) NOT NULL,
    sueldo_base NUMBER(10,2) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero VARCHAR2(20) NOT NULL,
    estado_civil VARCHAR2(20) NOT NULL,
    telefono_movil VARCHAR2(15) NOT NULL,
    direccion VARCHAR2(100) NOT NULL,
    cod_comuna NUMBER(4) NOT NULL,
    cod_nacionalidad NUMBER,
    tipo_trabajador VARCHAR2(1) NOT NULL,
    CONSTRAINT UQ_TRABAJADOR_RUT UNIQUE (rut),
    CONSTRAINT CK_TRABAJADOR_TIPO
        CHECK (tipo_trabajador IN ('J','P')),
    CONSTRAINT FK_TRABAJADOR_COMUNA
        FOREIGN KEY (cod_comuna) REFERENCES COMUNA(cod_comuna),
    CONSTRAINT FK_TRABAJADOR_NACIONALIDAD
        FOREIGN KEY (cod_nacionalidad)
        REFERENCES NACIONALIDAD(cod_nacionalidad)
);

CREATE TABLE JUGADOR (
    cod_trabajador NUMBER(6) CONSTRAINT PK_JUGADOR PRIMARY KEY,
    puesto VARCHAR2(30) NOT NULL,
    premios_acumulados NUMBER(12,2) DEFAULT 0 NOT NULL,
    cod_escuela NUMBER(6),
    anio_fin_amateur NUMBER(4),
    cod_asociacion NUMBER(6) NOT NULL,
    CONSTRAINT FK_JUGADOR_TRABAJADOR
        FOREIGN KEY (cod_trabajador)
        REFERENCES TRABAJADOR(cod_trabajador),
    CONSTRAINT FK_JUGADOR_ESCUELA
        FOREIGN KEY (cod_escuela)
        REFERENCES ESCUELA_FUTBOL(cod_escuela),
    CONSTRAINT FK_JUGADOR_ASOCIACION
        FOREIGN KEY (cod_asociacion)
        REFERENCES ASOCIACION(cod_asociacion),
    CONSTRAINT CK_JUGADOR_PREMIOS
        CHECK (premios_acumulados >= 0)
);

CREATE TABLE PERSONAL_PLANTA (
    cod_trabajador NUMBER(6) CONSTRAINT PK_PERSONAL_PLANTA PRIMARY KEY,
    cantidad_horas NUMBER(4),
    valor_horas_extras NUMBER(10,2),
    CONSTRAINT FK_PERSONAL_TRABAJADOR
        FOREIGN KEY (cod_trabajador)
        REFERENCES TRABAJADOR(cod_trabajador),
    CONSTRAINT CK_PERSONAL_HORAS
        CHECK (cantidad_horas IS NULL OR cantidad_horas >= 0),
    CONSTRAINT CK_PERSONAL_VALOR_HORAS
        CHECK (valor_horas_extras IS NULL OR valor_horas_extras >= 0)
);

-- 3. HISTORIAL DE CLUBES E IDIOMAS

CREATE TABLE HISTORIAL_CLUB (
    cod_trabajador NUMBER(6) NOT NULL,
    cod_club NUMBER(6) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    CONSTRAINT PK_HISTORIAL_CLUB
        PRIMARY KEY (cod_trabajador, cod_club, fecha_inicio),
    CONSTRAINT FK_HISTORIAL_JUGADOR
        FOREIGN KEY (cod_trabajador)
        REFERENCES JUGADOR(cod_trabajador),
    CONSTRAINT FK_HISTORIAL_CLUB
        FOREIGN KEY (cod_club)
        REFERENCES CLUB_FUTBOL(cod_club),
    CONSTRAINT CK_HISTORIAL_FECHAS
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE IDIOMA (
    cod_idioma NUMBER(4) CONSTRAINT PK_IDIOMA PRIMARY KEY,
    nombre_idioma VARCHAR2(50) NOT NULL,
    CONSTRAINT UQ_IDIOMA_NOMBRE UNIQUE (nombre_idioma)
);

CREATE TABLE JUGADOR_IDIOMA (
    cod_trabajador NUMBER(6) NOT NULL,
    cod_idioma NUMBER(4) NOT NULL,
    nivel_dominio VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_JUGADOR_IDIOMA
        PRIMARY KEY (cod_trabajador, cod_idioma),
    CONSTRAINT FK_JUGADOR_IDIOMA_JUGADOR
        FOREIGN KEY (cod_trabajador)
        REFERENCES JUGADOR(cod_trabajador),
    CONSTRAINT FK_JUGADOR_IDIOMA_IDIOMA
        FOREIGN KEY (cod_idioma)
        REFERENCES IDIOMA(cod_idioma)
);

