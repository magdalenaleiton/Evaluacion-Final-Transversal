-- 19. Consulta 1:
-- Asociaciones profesionales creadas desde el ano 2001

SELECT nombre_asociacion, fecha_creacion
FROM ASOCIACION
WHERE tipo = 'P'
AND fecha_creacion >= DATE '2001-01-01'
ORDER BY fecha_creacion DESC;

-- 20. Consulta 2:
-- Clubes con la letra a y patrimonio mayor a 200 millones
-- Se muestra el patrimonio en pesos y en dolares

SELECT c.cod_club, c.nombre_club, c.patrimonio,
       ROUND(c.patrimonio / 955, 2) AS patrimonio_usd
FROM CLUB_FUTBOL c
JOIN ASOCIACION a
ON c.cod_asociacion = a.cod_asociacion
WHERE LOWER(c.nombre_club) LIKE '%a%'
AND c.patrimonio > 200000000
AND a.tipo = 'P'
ORDER BY c.cod_club DESC;
